def test_audited_base_environment_contains_no_injection_variables() -> None:
    names = {entry.partition("=")[0] for entry in AUDITED_IMAGE_ENV}
    assert names == {"PATH", "GPG_KEY", "PYTHON_VERSION", "PYTHON_SHA256"}
    assert names.isdisjoint(
        {"LD_PRELOAD", "LD_AUDIT", "LD_LIBRARY_PATH", "PYTHONPATH", "PYTHONHOME"}
    )
