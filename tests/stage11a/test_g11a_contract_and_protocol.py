def test_a_published_build_round_trips_geom_type(tmp_path: Path) -> None:
    """The field survives ``publication.py``'s ``tag_fingerprints`` write and the
    baseline read back off it — the leg that makes it usable *after* the worker
    that computed it has exited."""
    from hephaestus.core.executor.runner import BuildRequest, run_build
    from hephaestus.core.executor.sandbox.unsafe import UnsafeLocalBackend
    from hephaestus.core.project_store.layout import load_project, open_store
    from hephaestus.core.project_store.publication import Publisher
    from hephaestus.testing.tools_fixture import scaffold

    root = tmp_path / "proj"
    scaffold(root)
    script = (
        "plate = Box(40, 40, 10)\n"
        "bored = plate - Cylinder(radius=5.0, height=40)\n"
        'tag(bored.faces().filter_by(GeomType.CYLINDER)[0], "bore_face")\n'
        'tag(bored.faces().filter_by(GeomType.PLANE).sort_by(SortBy.AREA)[-1], "top_face")\n'
        "part.geometry = bored\n"
    )
    (root / "parts" / "plate.py").write_text(script, encoding="utf-8")
    layout = load_project(root)
    store = open_store(layout)
    try:
        publisher = Publisher(layout, store)
        frozen = publisher.freeze_inputs("plate")
        build = run_build(
            BuildRequest(part="plate", script=frozen.script, globals_source=frozen.globals_source),
            backend=UnsafeLocalBackend(),
            out_dir=layout.store_root / "builds" / "plate-1",
        )
        assert build.result.status == "ok", build.result.error
        assert build.tag_fingerprints["bore_face"].geom_type == "CYLINDER"
        outcome = publisher.publish_build(build, op_id="pub-1")
        assert outcome.kind == "current", outcome.details

        baseline = publisher.baseline_for("plate")
        assert baseline is not None
        reloaded = dict(baseline.descriptors)
        assert reloaded["bore_face"].geom_type == "CYLINDER"
        assert reloaded["top_face"].geom_type == "PLANE"
    finally:
        store.close()


def test_the_worker_computes_geom_type_from_the_real_adaptor(tmp_path: Path) -> None:
    """In the worker, where the shape lives: the scratch tree holding the BRep
    is deleted in a ``finally`` before any caller sees it, so nowhere else
    *can* compute this."""
    from hephaestus.core.executor import worker

    out = tmp_path / "out"
    out.mkdir()
    script = (
        "plate = Box(30, 20, 6)\n"
        "bore = Cylinder(3, 20)\n"
        "body = plate - bore\n"
        "tag(body.faces().filter_by(GeomType.PLANE).sort_by(SortBy.AREA)[-1], 'top')\n"
        "tag(body.faces().filter_by(GeomType.CYLINDER)[0], 'bore')\n"
        "tag(body.edges().filter_by(GeomType.CIRCLE)[0], 'rim')\n"
        "tag(body.edges().filter_by(GeomType.LINE).sort_by(SortBy.LENGTH)[-1], 'edge')\n"
        "tag(body.solids()[0], 'whole')\n"
        "part.geometry = body\n"
    )
    result = worker.execute_job(
        {
            "part": "unit",
            "script": script,
            "globals_source": None,
            "part_overrides": {},
            "project_overrides": {},
            "out_dir": str(out),
        }
    )
    assert result["status"] == "ok", result.get("error")
    fingerprints = cast("dict[str, Any]", result["tag_fingerprints"])
    observed = {
        name: (cast("dict[str, Any]", entry)["kind"], cast("dict[str, Any]", entry)["geom_type"])
        for name, entry in fingerprints.items()
    }
    assert observed == {
        "top": ("face", "PLANE"),
        "bore": ("face", "CYLINDER"),
        "rim": ("edge", "CIRCLE"),
        "edge": ("edge", "LINE"),
        "whole": ("solid", "OTHER"),
    }
    for _name, entry in fingerprints.items():
        assert cast("dict[str, Any]", entry)["geom_type"] in GEOM_TYPES


