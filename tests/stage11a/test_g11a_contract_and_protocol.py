    row = index_of(root).get("stepper_nema17_frame").search_result()
    assert row["component_class"] == "motor"
    interfaces = cast("list[dict[str, Any]]", row["interfaces"])
    assert [entry["name"] for entry in interfaces] == ["mount_face", "shaft"]


