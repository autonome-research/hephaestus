def test_the_generated_artifacts_regenerate_identically() -> None:
    """All five: the JSON schemas, the TypeBox module, the MCP file, the docs.

    The declaration is artifact one and the source of the other four, so the
    per-tool schema set is asserted to *be* the declared tool set rather than
    merely to regenerate — a tool declared and never generated would otherwise
    pass every equality below.
    """
    generated = toolgen.generate_json_schemas()
    assert generated == toolgen.generate_json_schemas(), "generation is not deterministic"
    assert {Path(rel).name.removesuffix(".schema.json") for rel in generated} == set(
        tools_decl.tool_names()
    )
    for rel, text in generated.items():
        assert (REPO / rel).read_text(encoding="utf-8") == text, f"{rel} is stale; rerun toolgen"
    ts = (REPO / "agent" / "src" / "tools" / "schema.gen.ts").read_text(encoding="utf-8")
    assert ts == toolgen.generate_typebox_module(), "schema.gen.ts is stale; rerun toolgen"
    mcp = (REPO / "schemas" / "mcp" / "tools.json").read_text(encoding="utf-8")
    assert mcp == toolgen.generate_mcp_document(), "schemas/mcp/tools.json is stale; rerun toolgen"


def _tool_schema_md() -> str:
    return (REPO / "tool_schema.md").read_text(encoding="utf-8")


def test_the_fifth_artifact_is_reached_by_this_gates_own_command() -> None:
    """``tool_schema.md`` — the fifth of the five, and the one this gate's command
    did not reach.

    It is not generated by ``toolgen``; it is hand-maintained under a drift test
    (``contract/tests/test_toolgen.py``), and that suite is not part of either
    stage-11 gate's command. So the clause asserted "the five regenerate
    identically" while its own command could only see three of them. The drift
    contract is re-asserted here, in this gate, over the artifact this stage
    edited (the Amendment manifest's `tool_schema.md:1101-1114` row).
    """
    md = _tool_schema_md()
    declared = set(tools_decl.tool_names())
    excluded = set(tools_decl.STAGE2_EXCLUDED_TOOLS)

    # Every declared tool has a signature at column 0 inside a fence.
    signatures = set(re.findall(r"^([a-z][a-z0-9_]+)\(", md, re.MULTILINE))
    assert declared <= signatures, f"undocumented tools: {sorted(declared - signatures)}"

    # Every documented tool heading is declared, minus the recorded exclusions.
    headings: set[str] = set()
    for line in md.splitlines():
        if line.startswith("### "):
            headings |= {
                token.strip()
                for token in line[4:].split("/")
                if re.fullmatch(r"[a-z][a-z0-9_]+", token.strip())
            }
    assert not headings - excluded - declared, f"documented but undeclared: {headings - declared}"
    assert declared.isdisjoint(excluded)


